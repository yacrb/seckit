    install_go_tool "subfinder" "$root/tools/recon/subfinder" subfinder ./v2/cmd/subfinder .
    install_go_tool "amass" "$root/tools/recon/amass" amass ./cmd/amass .
    install_go_tool "httpx" "$root/tools/recon/httpx" httpx ./cmd/httpx .
    install_go_tool "nuclei" "$root/tools/recon/nuclei" nuclei ./cmd/nuclei .
    install_go_tool "naabu" "$root/tools/recon/naabu" naabu ./cmd/naabu .
    install_go_tool "gau" "$root/tools/recon/gau" gau .
    install_go_tool "ffuf" "$root/tools/web/ffuf" ffuf .
    install_go_tool "bettercap" "$root/tools/post/bettercap" bettercap ./cmd/bettercap .
    install_go_remote_tool "dnsx" dnsx github.com/projectdiscovery/dnsx/cmd/dnsx@latest

    install_python_package_tool "GraphQLmap" "$root/tools/web/GraphQLmap" "graphqlmap"
    install_python_script_tool "sqlmap" sqlmap "$root/tools/web/sqlmap" sqlmap.py
    install_python_script_tool "XSStrike" xsstrike "$root/tools/web/XSStrike" xsstrike.py requirements.txt
    install_python_script_tool "SSRFmap" ssrfmap "$root/tools/web/SSRFmap" ssrfmap.py requirements.txt
    install_python_script_tool "jwt_tool" jwt-tool "$root/tools/web/jwt_tool" jwt_tool.py requirements.txt
    install_ruby_script_tool "XXEinjector" xxeinjector "$root/tools/web/XXEinjector" XXEinjector.rb
    install_python_script_tool "AutoRecon" autorecon "$root/tools/exploitation/AutoRecon" autorecon.py requirements.txt
    install_python_script_tool "Volatility3" vol "$root/tools/forensics/volatility3" vol.py requirements-minimal.txt requirements.txt
    install_python_script_tool "Loki" loki "$root/tools/forensics/loki" loki.py requirements.txt
    install_python_script_tool "ScoutSuite" scoutsuite "$root/tools/cloud/ScoutSuite" ScoutSuite.py requirements.txt

    install_python_package_tool "plaso" "$root/tools/forensics/plaso" "log2timeline.py,psort.py"
    install_python_package_tool "pwntools" "$root/tools/crypto/pwntools" "pwn"
    install_python_package_tool "impacket" "$root/tools/cross/impacket" "GetNPUsers.py,GetUserSPNs.py,lookupsid.py,ntlmrelayx.py,psexec.py,secretsdump.py,smbclient.py,wmiexec.py"
    install_python_package_tool "pacu" "$root/tools/cloud/pacu" "pacu"
    install_python_package_tool "prowler" "$root/tools/cloud/prowler" "prowler"

    if [ -f "$root/tools/post/PEASS-ng/linPEAS/linpeas.sh" ]; then
        safe_symlink "linpeas" "$root/tools/post/PEASS-ng/linPEAS/linpeas.sh" "$BIN_DIR/linpeas"
    else
        record_status skipped "linpeas" "PEASS-ng submodule not initialized yet"
    fi

    if [ -f "$root/tools/exploitation/exploitdb/searchsploit" ]; then
        safe_symlink "searchsploit" "$root/tools/exploitation/exploitdb/searchsploit" "$BIN_DIR/searchsploit"
    else
        record_status skipped "searchsploit" "exploitdb checkout missing searchsploit"
    fi

    mark_repo_available "PowerSploit" "$root/tools/post/PowerSploit" "PowerShell toolkit repo available"
    mark_repo_available "mimikatz" "$root/tools/post/mimikatz" "source repo available for Windows builds"
    mark_repo_available "sigma" "$root/tools/forensics/sigma" "rules repo available"
    mark_repo_available "static-binaries" "$root/tools/cross/static-binaries" "portable binary collection available"
}

link_repo_scripts() {
    local script_path
    local launcher_name

    for script_path in "$SECKIT_ROOT"/scripts/*/*.sh; do
        if [ "$(basename "$(dirname "$script_path")")" = "lib" ]; then
            continue
        fi
        launcher_name="$(basename "$script_path" .sh)"
        safe_symlink "$launcher_name" "$script_path" "$BIN_DIR/$launcher_name"
    done
}

update_nuclei_templates() {
    if [ -x "$BIN_DIR/nuclei" ]; then
        if run_logged "nuclei template update" "$BIN_DIR/nuclei" -update-templates; then
            record_status installed "nuclei templates" "template cache refreshed"
        else
            record_status failed "nuclei templates" "template update failed"
        fi
    else
        record_status skipped "nuclei templates" "nuclei launcher unavailable"
    fi
}

print_manual_steps() {
    printf '\n[manual] Still user-managed by design:\n'
    printf '  - tools/windows/* GUI bundles remain manual downloads unless you add your own fetch automation.\n'
    printf '  - If a launcher was skipped because a file already existed in %s, the bootstrap intentionally left it alone.\n' "$BIN_DIR"
}

print_summary() {
    local line

    printf '\n==== SecKit Bootstrap Summary ====\n'

    printf '\nInstalled / updated:\n'
    if [ "${#INSTALLED[@]}" -eq 0 ]; then
        printf '  - none\n'
    else
        for line in "${INSTALLED[@]}"; do
            printf '  - %s\n' "$line"
        done
    fi

    printf '\nSkipped / preserved:\n'
    if [ "${#SKIPPED[@]}" -eq 0 ]; then
        printf '  - none\n'
    else
        for line in "${SKIPPED[@]}"; do
            printf '  - %s\n' "$line"
        done
    fi

    printf '\nFailed:\n'
    if [ "${#FAILED[@]}" -eq 0 ]; then
        printf '  - none\n'
    else
        for line in "${FAILED[@]}"; do
            printf '  - %s\n' "$line"
        done
    fi

    print_manual_steps
}

main() {
    log "SecKit bootstrap starting from $SECKIT_ROOT"
    ensure_dirs
    ensure_bin_path_notice

    sync_submodules
    install_core_packages
    install_tool_launchers
    link_repo_scripts
    update_nuclei_templates
    print_summary
}

main "$@"
